export default function SocialLinks({
  socials,
  variant = "dark",
  location,
  className = "",
}: SocialLinksProps) {
  const buttonStyle =
    variant === "dark"
      ? "border-white/15 bg-white/5 text-sand-200/80 hover:text-oak-light hover:border-oak-light/60 hover:bg-white/10"
      : "border-sand-200 bg-[#FAF8F5] text-charcoal hover:text-oak hover:border-oak hover:bg-white";

  return (
    <div className={`flex flex-wrap items-center gap-2.5 ${className}`} role="list" aria-label="Social media channels">
      {socials.map((social) => (
        <a
          key={social.id}
          role="listitem"
          href={social.href}
          target="_blank"
          rel="noopener noreferrer"
          title={`${social.name} (${social.handle})`}
          aria-label={`Follow Maison Oak on ${social.name} (${social.handle})`}
          onClick={() =>
            trackEvent({
              name: "cta_click",
              properties: {
                label: `Social - ${social.name}`,
                location,
                targetHref: social.href,
              },
            })
          }
          className={`inline-flex h-9 w-9 items-center justify-center rounded-full border transition-all duration-200 focus:outline-none focus-visible:ring-2 focus-visible:ring-oak ${buttonStyle}`}
        >
          <SocialIcon id={social.id} size={16} />
        </a>
      ))}
    </div>
  );
}
